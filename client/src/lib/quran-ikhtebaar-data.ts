export function getDarajahSyllabus(nizam: NizamType, darajah: number): DarajahSyllabus | null {
  const nizamConfig = QURAN_IKHTEBAAR_DATA[nizam];
  if (!nizamConfig) return null;
  return nizamConfig.darajahs[darajah] || null;
}

export function getRandomizedExamPaper(nizam: NizamType, darajah: number, seed: number = 0): QuestionItem[] {
  const syl = getDarajahSyllabus(nizam, darajah);
  if (!syl) return [];

  const questions: QuestionItem[] = JSON.parse(JSON.stringify(syl.questionBank));

  if (seed > 0) {
    const rot = seed % questions.length;
    const rotated = [...questions.slice(rot), ...questions.slice(0, rot)];
    rotated.forEach((q, idx) => {
      q.qNumber = idx + 1;
    });
    return rotated;
  }

  return questions;
}
