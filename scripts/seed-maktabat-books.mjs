async function seedMaktabat() {
  console.log("📚 Seeding Maktabat (Library) books into database...");

  let addedCount = 0;
  let updatedCount = 0;

  for (const book of MAKTABAT_CATALOG) {
    const existing = await prisma.libraryBook.findUnique({
      where: { barcode: book.barcode },
    });

    if (existing) {
      await prisma.libraryBook.update({
        where: { barcode: book.barcode },
        data: {
          title: book.title,
          author: book.author,
          publisher: book.publisher,
          category: book.category,
          rackNumber: book.rackNumber,
          shelfNumber: book.shelfNumber,
          locationColor: book.locationColor,
          status: book.status,
          totalCopies: book.totalCopies,
          availableCopies: book.availableCopies,
          notes: book.notes,
        },
      });
      updatedCount++;
    } else {
      await prisma.libraryBook.create({
        data: book,
      });
      addedCount++;
    }
  }

  const total = await prisma.libraryBook.count();
  console.log(`✅ Maktabat Seeding Complete! Added: ${addedCount}, Updated: ${updatedCount}, Total Books in Database: ${total}`);
}

seedMaktabat()
  .then(async () => {
    await prisma.$disconnect();
  })
  .catch(async (e) => {
    console.error("❌ Seeding error:", e);
    await prisma.$disconnect();
    process.exit(1);
  });
